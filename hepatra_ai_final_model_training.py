# Define clinically valid ranges for each biomarker
VALID_RANGES = {
    'Age': (1, 120),
    'Gender': (0, 1),
    'AFP': (0, 10000),      # ng/mL - >1000 is extremely rare but possible
    'ALT': (1, 5000),       # U/L
    'AST': (1, 5000),       # U/L
    'Bilirubin': (0.1, 50), # mg/dL
    'Albumin': (0.5, 10),   # g/dL
    'Alk_Phos': (10, 5000), # IU/L
    'Hepatitis_B': (0, 1),
    'Hepatitis_C': (0, 1)
}

# Also define "suspicious" ranges (possible but should be flagged)
SUSPICIOUS_RANGES = {
    'AFP': (1000, 10000),   # Very high AFP - double-check
    'ALT': (500, 5000),     # Extremely elevated
    'AST': (500, 5000),     # Extremely elevated
    'Bilirubin': (20, 50),  # Severe jaundice range
    'Age': (90, 120)        # Very elderly - verify age
}

def validate_patient_data(patient_dict):
    """
    Validates a single patient's lab values.
    Returns: (is_valid, warnings, errors)
    """
    errors = []
    warnings = []

    for feature, (min_val, max_val) in VALID_RANGES.items():
        if feature in patient_dict:
            val = patient_dict[feature]
            if val < min_val or val > max_val:
                errors.append(f"❌ {feature} = {val} is OUT OF RANGE [{min_val}-{max_val}]")

    for feature, (min_val, max_val) in SUSPICIOUS_RANGES.items():
        if feature in patient_dict:
            val = patient_dict[feature]
            if min_val <= val <= max_val:
                warnings.append(f"⚠️  {feature} = {val} is SUSPICIOUS - please verify")

    is_valid = len(errors) == 0
    return is_valid, warnings, errors

