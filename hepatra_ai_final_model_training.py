print("📊 FEATURE 1: BOOTSTRAP CONFIDENCE INTERVALS")
print("=" * 70)

n_bootstrap = 100
auc_scores = []
accuracy_scores = []

# Combine train+test for bootstrap resampling
X_full = pd.concat([X_train, X_test], axis=0)
y_full = pd.concat([pd.Series(y_train), pd.Series(y_test)], axis=0).reset_index(drop=True)

print(f"Running {n_bootstrap} bootstrap iterations...")

for i in range(n_bootstrap):
    # Resample with replacement
    indices = np.random.choice(len(X_full), size=len(X_full), replace=True)
    X_boot = X_full.iloc[indices]
    y_boot = y_full.iloc[indices]

    # Split bootstrapped data
    split_idx = int(0.8 * len(X_boot))
    X_tr, X_te = X_boot.iloc[:split_idx], X_boot.iloc[split_idx:]
    y_tr, y_te = y_boot.iloc[:split_idx], y_boot.iloc[split_idx:]

    # Train quick model
    boot_model = XGBClassifier(
        n_estimators=100, max_depth=4, learning_rate=0.1,
        random_state=i, eval_metric='logloss', verbosity=0,
        use_label_encoder=False
    )
    boot_model.fit(X_tr, y_tr)

    # Score
    y_proba = boot_model.predict_proba(X_te)[:, 1]
    try:
        auc_scores.append(roc_auc_score(y_te, y_proba))
        accuracy_scores.append(accuracy_score(y_te, (y_proba >= 0.5).astype(int)))
    except:
        pass

# Calculate CIs
